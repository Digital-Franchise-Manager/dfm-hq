"""Append-only classic award history contract."""
from typing import Protocol
from .models import AwardRecord,CoachCredit
class AwardHistoryRepository(Protocol):
    def append_awards_once(self,awards:tuple[AwardRecord,...])->int: ...
    def append_coach_credits_once(self,credits:tuple[CoachCredit,...])->int: ...
    def list_awards(self,round_number:int|None=None)->tuple[AwardRecord,...]: ...
    def list_coach_credits(self,coach_id:str|None=None)->tuple[CoachCredit,...]: ...
